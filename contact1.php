//確認画面の入力内容出力用関数
function confirmOutput($arr){
	global $hankaku,$hankaku_array;
	$html = '';

	/*
	 * 入力フォームと同じ並びで表示する。
	 * POST の順序に頼ると環境によって前後するため、明示的に並べ替える。
	 * ここに無い項目は、そのあとに元の順で続く。
	 */
	$order = array('氏名','フリガナ','会社名','部署名','役職','TEL',
	               'メールアドレス','メールアドレス確認用','お問い合わせ内容',
	               'プライバシーポリシーへの同意');
	$sorted = array();
	foreach($order as $k){
		if(array_key_exists($k, $arr)) $sorted[$k] = $arr[$k];
	}
	foreach($arr as $k => $v){
		if(!array_key_exists($k, $sorted)) $sorted[$k] = $v;
	}
	$arr = $sorted;

	foreach($arr as $key => $val) {
		$out = '';
		if(is_array($val)){
			foreach($val as $key02 => $item){ 
				//連結項目の処理
				if(is_array($item)){
					$out .= connect2val($item);
				}else{
					$out .= $item . ', ';
				}
			}
			$out = rtrim($out,', ');
			
		}else{ $out = $val; }//チェックボックス（配列）追記ここまで
		
		$out = nl2br(h($out));//※追記 改行コードを<br>タグに変換
		$key = h($key);
		
		//全角→半角変換
		if($hankaku == 1){
			$out = zenkaku2hankaku($key,$out,$hankaku_array);
		}
		
		//確認画面は dl で組んでいるので、それに合わせて出力する
		$html .= '<div class="cconf__row"><dt>'.$key.'</dt><dd>'.$out;
		$html .= '<input type="hidden" name="'.$key.'" value="'.str_replace(array("<br />","<br>"),"",$out).'" />';
		$html .= "</dd></div>\n";
	}
	return $html;
}

//全角→半角変換
function zenkaku2hankaku($key,$out,$hankaku_array){
	global $encode;
	if(is_array($hankaku_array) && function_exists('mb_convert_kana')){
		foreach($hankaku_array as $hankaku_array_val){
			if($key == $hankaku_array_val){
				$out = mb_convert_kana($out,'a',$encode);
			}
		}
	}
	return $out;
}
//配列連結の処理
function connect2val($arr){
	$out = '';
	foreach($arr as $key => $val){
		if($key === 0 || $val == ''){//配列が未記入（0）、または内容が空のの場合には連結文字を付加しない（型まで調べる必要あり）
			$key = '';
		}elseif(strpos($key,"円") !== false && $val != '' && preg_match("/^[0-9]+$/",$val)){
			$val = number_format($val);//金額の場合には3桁ごとにカンマを追加
		}
		$out .= $val . $key;
	}
	return $out;
}

